"""Excel workbook export for a single deal — Summary · Returns · Rent Roll.

Brian's first-user feedback (2026-08): "download to Excel — they have letters
and memos already [the Artifact Engine Word docs], but they want the *numbers*
in a spreadsheet they can slice." This builds a deterministic, no-API workbook
straight from the same DealState + cash-flow projection the Exec Summary tab
already computes, so the download always matches what's on screen.

Deliberately deterministic (unlike the LLM Artifact Engine): a spreadsheet is a
model, not prose. The three sheets are:

  1. **Summary**   — property identity, headline metrics, verdict + rationale.
  2. **Returns**   — the 5-year cash-flow table row-for-row, the exit block,
                     and the IRR / equity-multiple line.
  3. **Rent Roll** — the parsed unit rows from `sources["rentRoll"]` when a
                     rent roll has been ingested; otherwise a single note row.

`build_workbook_bytes` returns the `.xlsx` as bytes so the caller can hand it
straight to `st.download_button` — nothing is written to disk here.
"""

from __future__ import annotations

from io import BytesIO
from typing import Any

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.worksheet import Worksheet

import config

# Eight Rock brand accent for header fills (openpyxl wants ARGB, no '#').
_ACCENT = config.COLORS.get("ac", "#C8900A").lstrip("#")
_HEADER_FILL = PatternFill("solid", fgColor=f"FF{_ACCENT}")
_HEADER_FONT = Font(bold=True, color="FFFFFFFF")
_LABEL_FONT = Font(bold=True)
_TITLE_FONT = Font(bold=True, size=14)

_MONEY = "#,##0"
_MONEY2 = "#,##0.00"
_PCT = "0.0%"
_MULT = "0.00\"x\""


def _title(ws: Worksheet, text: str) -> None:
    ws["A1"] = text
    ws["A1"].font = _TITLE_FONT


def _header_row(ws: Worksheet, row: int, labels: list[str]) -> None:
    for col, label in enumerate(labels, start=1):
        cell = ws.cell(row=row, column=col, value=label)
        cell.fill = _HEADER_FILL
        cell.font = _HEADER_FONT
        cell.alignment = Alignment(horizontal="center")


def _kv(ws: Worksheet, row: int, label: str, value: Any,
        num_fmt: str | None = None) -> None:
    ws.cell(row=row, column=1, value=label).font = _LABEL_FONT
    cell = ws.cell(row=row, column=2, value=value)
    if num_fmt is not None and value is not None:
        cell.number_format = num_fmt


def _autosize(ws: Worksheet, widths: dict[int, int]) -> None:
    for col, width in widths.items():
        ws.column_dimensions[get_column_letter(col)].width = width


