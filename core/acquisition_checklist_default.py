def all_items() -> tuple[Item, ...]:
    """Flatten the catalog to a single tuple of items."""
    out: list[Item] = []
    for phase in ACQUISITION_CHECKLIST:
        for cat in phase.categories:
            out.extend(cat.items)
    return tuple(out)


def find_item(item_id: str) -> Item | None:
    """Look up an item by its stable id. Returns None if not found."""
    for item in all_items():
        if item.id == item_id:
            return item
    return None
