def _derive_year1(deal: DealState, sources: dict[str, Any] | None) -> tuple[float, float]:
    if sources:
        rev = sources.get("totalRevenue")
        opex = sources.get("totalOpex")
        if rev and opex:
            try:
                rev_v = rev.get("value") if isinstance(rev, dict) else rev
                opex_v = opex.get("value") if isinstance(opex, dict) else opex
                if rev_v and opex_v:
                    return float(rev_v), float(opex_v)
            except (AttributeError, TypeError, ValueError):
                pass
    er = config.EXPENSE_RATIOS.get("C", 0.45)
    vac = deal.vacancy_frac
    denom = (1.0 - vac - er)
    gpr = deal.noi / denom if denom > 0 else deal.noi / 0.5
    return gpr, gpr * er


def _save_api_key_to_env(env_path: Path, key: str) -> None:
    """Write `ANTHROPIC_API_KEY=<key>` into the workbench's local `.env`.

    Preserves any other lines already in the file (e.g. future settings).
    If a `ANTHROPIC_API_KEY=` line already exists it gets replaced rather
    than duplicated. Atomic via tempfile + replace so a crash mid-write
    can't corrupt the file.
    """
    import re as _re
    import tempfile as _tempfile

    new_line = f"ANTHROPIC_API_KEY={key}"
    if env_path.is_file():
        existing = env_path.read_text(encoding="utf-8")
        if _re.search(r"^\s*ANTHROPIC_API_KEY\s*=", existing, _re.M):
            new_content = _re.sub(
                r"^\s*ANTHROPIC_API_KEY\s*=.*$",
                new_line,
                existing,
                flags=_re.M,
            )
        else:
            new_content = existing.rstrip("\n") + "\n" + new_line + "\n"
    else:
        new_content = (
            "# Eight Rock Workbench — local secrets (gitignored).\n"
            "# Generated by the in-app setup flow.\n"
            f"{new_line}\n"
        )

    env_path.parent.mkdir(parents=True, exist_ok=True)
    with _tempfile.NamedTemporaryFile(
        mode="w", encoding="utf-8", dir=str(env_path.parent),
        delete=False, suffix=".tmp",
    ) as tmp:
        tmp.write(new_content)
        tmp_path = Path(tmp.name)
    tmp_path.replace(env_path)


def _money(v: Any) -> str:
    if v is None:
        return "—"
    try:
        return f"${float(v):,.0f}"
    except (TypeError, ValueError):
        return str(v)


def _pct(v: Any, decimals: int = 2) -> str:
    if v is None:
        return "—"
    try:
        return f"{float(v) * 100:.{decimals}f}%"
    except (TypeError, ValueError):
        return str(v)


