def _build_summary_data(prop: dict[str, Any], folder: PropertyFolder | None):
    if folder is None:
        return None
    deal = load_deal(folder.path)
    if deal is None:
        return None
    sources = load_sources(folder.path)
    gpr, expenses = _derive_year1(deal, sources)

    debt_terms = DebtTerms(
        loan_amount=deal.loan_amount,
        annual_rate=deal.interest_rate,
        amort_months=config.AMORT_MONTHS,
        io_years=deal.io,
    )
    debt_sched = build_debt_schedule(debt_terms, deal.hp)
    cf = build_cashflow(
        year1_gpr=gpr,
        year1_vacancy_pct=deal.vacancy_frac,
        year1_expenses=expenses,
        rent_growth=deal.rent_growth,
        expense_growth=deal.expense_growth,
        am_fee_pct=deal.am_fee_pct,
        debt=debt_sched,
        hold_years=deal.hp,
        exit_cap=deal.exit_cap,
        equity_raise=deal.equity_raise,
    )
    pots = [r.cash_flow for r in cf.rows[:-1]] + [
        cf.rows[-1].cash_flow + cf.exit_proceeds_net
    ]
    wf = run_waterfall(equity_raise=deal.equity_raise, annual_pots=pots)
    lp_rate = lp_irr(wf.lp_cashflows)
    proj_rate = project_irr(
        equity_raise=deal.equity_raise,
        annual_cashflows=[r.cash_flow for r in cf.rows],
        exit_proceeds_net=cf.exit_proceeds_net,
    )
    em = equity_multiple(deal.equity_raise, wf.total_lp_distributions)
    cap = deal.noi / deal.pp if deal.pp else 0.0
    ads = debt_sched.annual_payment[0]
    dscr_v = (deal.noi - deal.am_fee_pct * gpr) / ads if ads else 0.0
    coc = cf.rows[0].coc
    ppu = deal.pp / (prop.get("units") or 1)

    verdict = evaluate(
        cap=cap, dscr=dscr_v, coc=coc, ppu=ppu,
        city=prop.get("city") or "",
    )

    # Sensitivity grid
    sens_base = SensitivityBase(
        purchase_price=deal.pp,
        year1_gpr=gpr, year1_expenses=expenses,
        am_fee_pct=deal.am_fee_pct,
        loan_amount=deal.loan_amount,
        annual_rate=deal.interest_rate,
        amort_months=config.AMORT_MONTHS, io_years=deal.io,
        hold_years=deal.hp, exit_cap=deal.exit_cap,
        equity_raise=deal.equity_raise,
    )
    sens = build_sensitivity(sens_base)

    # ---- Module E (§6.3): named stress overlays + QA + DD tightening -----
    from core import verdict_tightening
    from core.extraction_qa import run_qa
    from core.stress_overlays import run_stress_overlays

    stress = run_stress_overlays(
        sens_base,
        base_vacancy=deal.vacancy_frac,
        base_rent_growth=deal.rent_growth,
        base_expense_growth=deal.expense_growth,
    )
    qa_report = run_qa(sources or {})

    # DD only tightens once diligence has actually started (dd.json exists);
    # bootstrapping a 0%-complete file here would demote every fresh deal.
    dd_state = None
    if (folder.path / "dd.json").is_file():
        from core import due_diligence as dd_mod
        dd_state = dd_mod.recompute_aggregates(dd_mod.load_state(folder.path))

    tight = verdict_tightening.tighten(
        verdict, dd_state=dd_state, stress=stress, qa=qa_report)

    return {
        "deal": deal, "sources": sources, "cf": cf, "wf": wf,
        "lp_irr": lp_rate, "project_irr": proj_rate, "equity_multiple": em,
        "cap": cap, "dscr": dscr_v, "coc": coc, "ppu": ppu,
        "ads": ads, "gpr_y1": gpr, "expenses_y1": expenses,
        "verdict": verdict, "sensitivity": sens,
        "stress": stress, "qa": qa_report, "tightened": tight,
        "dd_started": dd_state is not None,
    }


